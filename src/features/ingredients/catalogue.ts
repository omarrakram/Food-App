import { GENERATED_INGREDIENTS } from './catalogue.generated.ts';
import type { Allergen, IngredientCategory, Unit } from '@/types/domain';

/**
 * Canonical ingredient catalogue for the Egyptian launch market.
 *
 * The catalogue data itself lives in data/ingredients/catalogue.csv and is
 * generated into `catalogue.generated.ts`; this file owns the type, the
 * derived indexes, and nothing else. The catalogue is:
 *   1. bundled into the app for offline autocomplete and matching, and
 *   2. compiled into `supabase/seed.sql` by `scripts/generate-seed.ts`.
 *
 * After editing, run `npm run seed:generate` and commit the regenerated SQL.
 *
 * NOTE: this module must only use `import type` so the seed generator can load
 * it with Node's type-stripping loader.
 */

export type CatalogueIngredient = {
  /** Stable slug. Becomes the ingredient's natural key in Postgres. */
  slug: string;
  name: string;
  nameAr: string;
  category: IngredientCategory;
  defaultUnit: Unit;
  /** Grams in one `piece`. Null for ingredients that are not countable. */
  gramsPerPiece: number | null;
  allergens: Allergen[];
  /** Match aliases: transliterations, Arabic spellings, regional names, plurals. */
  aliases: string[];
  /** Assumed present in most kitchens unless the user says otherwise. */
  isCommonStaple: boolean;
  /** Spoils quickly; expiry dates are enforced strictly for these. */
  isPerishable: boolean;
};

/*
 * NOTE: prices deliberately do NOT live here.
 *
 * Recognising an ingredient and knowing what it costs are separate problems
 * with separate data. Keeping them in one record meant every new ingredient
 * needed a price before it could be added — which is how you end up inventing
 * figures to fill a table. Prices live in data/prices/eg.csv, are imported by
 * `npm run prices:import`, and are keyed by the slug above. An ingredient with
 * no price row is a normal, supported state.
 */

/**
 * Every ingredient the app can recognise.
 *
 * Authored in data/ingredients/catalogue.csv and generated by
 * `npm run ingredients:import`, so adding a food is a row in a sheet rather
 * than an edit to application code. The importer rejects duplicate slugs,
 * unknown categories and — most importantly — any alias claimed by two
 * ingredients, which would otherwise silently bind a word to whichever entry
 * loaded first.
 */
export const INGREDIENT_CATALOGUE: readonly CatalogueIngredient[] = GENERATED_INGREDIENTS;

/** Fast lookup by slug. */
export const INGREDIENTS_BY_SLUG = new Map(
  INGREDIENT_CATALOGUE.map((ingredient) => [ingredient.slug, ingredient]),
);

/** Ingredients assumed present in nearly every kitchen. */
export const COMMON_STAPLE_SLUGS = INGREDIENT_CATALOGUE.filter((i) => i.isCommonStaple).map(
  (i) => i.slug,
);
