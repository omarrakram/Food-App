/** Every literal key present in the dictionary, plural variants included. */
export type RawTranslationKey = keyof typeof en;

/**
 * Base name of a pluralised key: `common.servings_one` -> `common.servings`.
 * Call sites pass the base plus a `count` and `t()` picks the variant.
 */
export type PluralBaseKey<K extends string = RawTranslationKey> = K extends `${infer Base}_one`
  ? Base
  : K extends `${infer Base}_other`
    ? Base
    : never;

/** What `t()` accepts: any literal key, or the base of a pluralised one. */
export type TranslationKey = RawTranslationKey | PluralBaseKey;

export type TranslationDictionary = Partial<Record<RawTranslationKey, string>>;
